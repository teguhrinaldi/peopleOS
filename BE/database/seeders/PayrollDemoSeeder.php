    public function run(): void
    {
        $company = Company::query()->where('name', 'PeopleOS Demo Company')->first();
        $admin = User::query()->where('email', 'admin@peopleos.test')->first();
        $hr = User::query()->where('email', 'hr@peopleos.test')->first();
        if (! $company || ! $admin || ! $hr) {
            $this->command?->warn('PayrollDemoSeeder: run DemoSeeder first.');

            return;
        }
        if (SalaryComponent::query()->where('company_id', $company->id)->exists()) {
            $this->command?->warn('PayrollDemoSeeder: payroll demo data already present, skipped.');

            return;
        }

        [$this->company, $this->admin, $this->hr] = [$company, $admin, $hr];
        app(CompanyContext::class)->forget();
        mt_srand(2603);

        try {
            $this->at('2025-12-15 09:00');
            $this->catalog();
            app(OvertimeRuleService::class)->create($this->admin, OvertimeDemoSeeder::demoRule());
            app(Settings::class)->set(['overtime.engine_enabled' => true]);
            $structures = $this->structures();
            $this->assignSalaries($structures);
            $this->raises();

            Carbon::setTestNow();
            $this->backfillAttendance();
            $this->overtime();

            $this->closedMonth('2026-07-01', '2026-07-31', '2026-07-31', 'TRF-2026-07-31');
            $this->closedMonth('2026-08-01', '2026-08-31', '2026-08-31', 'TRF-2026-08-31');
            $this->september();
        } finally {
            Carbon::setTestNow();
        }

        $this->call(OvertimeDemoSeeder::class);
    }

    private function at(string $local): void
    {
        Carbon::setTestNow(CarbonImmutable::parse($local, $this->company->timezone ?: 'Asia/Jakarta'));
    }

