/**
 * Payroll demo data for the DemoSeeder company. ALL amounts are illustrative demo values in the configured
 * currency (IDR by default) - not statutory rates, not tax rules. Everything goes through the real services
 * so the audit trail, snapshots, payslip numbers and PDFs are exactly what a real run produces.
 *
 *  - catalog: Basic Salary, Transport / Meal (per present day), Position Allowance, Overtime (per hour),
 *    Unpaid Leave deduction, Cooperative Savings, Other Earnings / Other Deductions
 *  - structures: Staff, Manager; every employee assigned from 2026-01-01 (or their join date)
 *  - raises: Michael Carter 8,000,000 -> 9,000,000 from 2026-07-01; Olivia Martin 7,000,000 -> 7,400,000 from 2026-09-01
