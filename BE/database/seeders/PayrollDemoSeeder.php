        $c = fn (string $code, $amount = null) => ['salary_component_id' => $this->components[$code]->id, 'amount' => $amount];

        return [
            'STAFF' => $service->save($this->hr, null, ['code' => 'STAFF', 'name' => 'Staff', 'description' => 'Non-managerial employees.'], [
