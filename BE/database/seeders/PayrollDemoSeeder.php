    /** @param array<string, SalaryStructure> $structures */
    private function assignSalaries(array $structures): void
    {
        $service = app(SalaryStructureService::class);
        $employees = Employee::query()->where('company_id', $this->company->id)->get()->keyBy('employee_number');

        foreach (self::SALARIES as $number => [$structure, $basic, $position]) {
            $employee = $employees->get($number);
            if (! $employee) {
                continue;
            }
            $overrides = [$this->components['BASIC']->id => ['amount' => (string) $basic]];
            if ($position !== null) {
                $overrides[$this->components['POSITION']->id] = ['amount' => (string) $position];
            }
            $from = max('2026-01-01', $employee->join_date->toDateString());
            $service->assign($this->hr, $structures[$structure], $employee, $from, 'Initial salary', $overrides);
        }
    }

    private function raises(): void
    {
        $service = app(EmployeeSalaryService::class);
        foreach ([
            ['EMP-0012', '2026-06-25 10:00', '2026-07-01', '9000000', 'Annual review: performance raise'],
            ['EMP-0013', '2026-08-25 10:00', '2026-09-01', '7400000', 'Contract renewal'],
        ] as [$number, $decidedAt, $from, $amount, $reason]) {
            $employee = Employee::query()->where('company_id', $this->company->id)->where('employee_number', $number)->first();
            if ($employee) {
                $this->at($decidedAt);
                $service->change($this->hr, $employee, $from, [['salary_component_id' => $this->components['BASIC']->id, 'amount' => $amount]], $reason);
            }
        }
    }

    /**
     * DemoSeeder only creates the last 21 days of attendance; payroll needs July and August too.
     * Fills every scheduled working day from 2026-07-01 that has no attendance yet (same style: ~4 % absent, some late).
     */
    private function backfillAttendance(): void
    {
        $schedules = app(ScheduleService::class);
        $attendance = app(AttendanceService::class);
        $today = app(CompanyContext::class)->today();

        $employees = Employee::query()->where('company_id', $this->company->id)
            ->whereIn('status', [EmployeeStatus::Active->value, EmployeeStatus::Terminated->value])->orderBy('employee_number')->get();

        foreach ($employees as $employee) {
            $existing = Attendance::query()->where('employee_id', $employee->id)->pluck('work_date')->map(fn ($d) => $d->toDateString())->flip();
            $last = $employee->terminated_at ? min($employee->terminated_at->toDateString(), $today->subDay()->toDateString()) : $today->subDay()->toDateString();
            $day = CarbonImmutable::parse(max('2026-07-01', $employee->join_date->toDateString()));

            for (; $day->toDateString() <= $last; $day = $day->addDay()) {
                if (isset($existing[$day->toDateString()])) {
                    continue;
                }
                $schedule = $schedules->forDate($employee, $day->toDateString());
                if (! $schedule->is_working_day || mt_rand(1, 100) <= 4) {
                    continue;
                }
                $late = mt_rand(1, 100) <= 15 ? mt_rand(12, 40) : mt_rand(-12, 4);
                $in = CarbonImmutable::instance($schedule->expected_start_at)->addMinutes($late);
                $out = CarbonImmutable::instance($schedule->expected_end_at)->addMinutes(mt_rand(-3, 25));

                $row = new Attendance([
                    'employee_id' => $employee->id, 'attendance_schedule_id' => $schedule->id, 'work_date' => $day->toDateString(),
                    'status' => AttendanceStatus::CheckedOut, 'check_in_at' => $in, 'check_out_at' => $out,
                ]);
                $attendance->recalculate($row, $schedule);
                $row->save();

                foreach ([[AttendanceEventType::CheckIn, $in], [AttendanceEventType::CheckOut, $out]] as [$type, $at]) {
                    AttendanceEvent::query()->create([
                        'attendance_id' => $row->id, 'employee_id' => $employee->id, 'type' => $type,
                        'idempotency_key' => sprintf('demo-%d-%s-%s', $employee->id, $day->toDateString(), $type->value),
                        'occurred_at' => $at, 'received_at' => $at, 'time_source' => 'server',
                        'latitude' => $schedule->location_latitude, 'longitude' => $schedule->location_longitude,
                        'accuracy_meters' => mt_rand(60, 250) / 10, 'location_captured_at' => $at,
                        'distance_meters' => mt_rand(5, 60), 'inside_geofence' => true,
                    ]);
                }
            }
        }
    }

    private function overtime(): void
    {
        $tz = $this->company->timezone ?: 'Asia/Jakarta';
        foreach (self::OVERTIME as $number => $entries) {
            $employee = Employee::query()->where('company_id', $this->company->id)->where('employee_number', $number)->first();
            foreach ($entries as [$date, $minutes]) {
                $start = CarbonImmutable::parse("{$date} 17:30", $tz)->utc();
                $this->stayLate($employee, $date, $start->addMinutes($minutes + 5));
                $request = OvertimeRequest::query()->create([
                    'employee_id' => $employee->id, 'work_date' => $date, 'start_at' => $start, 'end_at' => $start->addMinutes($minutes),
                    'requested_minutes' => $minutes, 'approved_minutes' => $minutes, 'reason' => 'Month-end workload.',
                    'status' => RequestStatus::Approved, 'requested_by' => $employee->user_id, 'reviewed_by' => $this->hr->id,
                    'reviewed_at' => CarbonImmutable::parse("{$date} 20:00", $tz)->utc(), 'payroll_status' => OvertimeRequest::PAYROLL_PENDING,
                ]);
                $check = app(OvertimeEligibility::class)->evaluate($request);
                $request->fill([
                    'day_type' => $check['day_type'], 'verified_minutes' => $check['verified'],
                    'verification_status' => $check['status'], 'verified_at' => $request->reviewed_at,
                ])->save();
            }
        }
    }

    /** The employee really stayed: the attendance of that date ends after the overtime (row created when absent). */
    private function stayLate(Employee $employee, string $date, CarbonImmutable $checkOut): void
    {
        $schedule = app(ScheduleService::class)->forDate($employee, $date);
        $row = Attendance::query()->where('employee_id', $employee->id)->whereDate('work_date', $date)->first()
            ?? new Attendance([
                'employee_id' => $employee->id, 'attendance_schedule_id' => $schedule->id, 'work_date' => $date,
                'check_in_at' => $schedule->expected_start_at,
            ]);
        $row->fill(['status' => AttendanceStatus::CheckedOut, 'check_out_at' => $checkOut]);
        app(AttendanceService::class)->recalculate($row, $schedule);
        $row->save();
    }

    private function closedMonth(string $start, string $end, string $payDate, string $reference): void
    {
        $this->at("{$end} 10:00");
        $period = app(PayrollPeriodService::class)->createRegular($this->hr, $start, $end, null, $payDate, 'Monthly payroll');
        $this->at("{$end} 11:00");
        app(PayrollGenerator::class)->generate($this->hr, $period);
        $this->at("{$end} 11:30");
        app(PayrollWorkflow::class)->submit($this->hr, $period);
        $this->at("{$end} 14:00");
        app(PayrollWorkflow::class)->approve($this->admin, $period);
        $this->at("{$end} 15:00");
        app(PayrollWorkflow::class)->finalize($this->admin, $period);
        $this->at("{$end} 16:30");
        app(PayrollWorkflow::class)->markPaid($this->admin, $period, $reference);
    }

    /** Generated and submitted by HR, waiting for the Admin's approval. */
    private function september(): void
    {
        $this->at('2026-09-28 09:00');
        $period = app(PayrollPeriodService::class)->createRegular($this->hr, '2026-09-01', '2026-09-30', null, '2026-09-30', 'Monthly payroll');
        Carbon::setTestNow();
        app(PayrollGenerator::class)->generate($this->hr, $period);
        app(PayrollWorkflow::class)->submit($this->hr, $period);

        $this->command?->info('Payroll demo: '.PayrollPeriod::query()->count().' periods; September is in REVIEW for the Admin.');
    }
